import { createRequire } from 'module';
import fs from 'fs';
import path from 'path';
const require = createRequire('/Users/titus/.npm/_npx/e41f203b7505f1fb/node_modules/');
const { chromium } = require('playwright');
const dir = process.argv[2];
const out = process.argv[3];
const files = fs.readdirSync(dir).filter(f => /\.(png|svg|ico|webp)$/.test(f)).sort();
const extra = (process.argv[4]||'').split(',').filter(Boolean);
let html = '<html><body style="margin:0;background:#ddd;font:12px sans-serif;display:flex;flex-wrap:wrap;gap:10px;padding:10px">';
for (const f of [...files.map(f=>'file://'+path.join(dir,f)), ...extra]) html += `<div style="background:#fff;padding:6px;text-align:center"><img src="${f}" style="width:140px;height:140px;object-fit:contain;display:block"><div>${path.basename(f).slice(0,24)}</div></div>`;
html += '</body></html>';
const tmp = path.join(path.dirname(out), 'sheet-tmp.html');
fs.writeFileSync(tmp, html);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1000, height: 600 } });
await p.goto('file://' + tmp);
await p.waitForTimeout(500);
await p.screenshot({ path: out, fullPage: true });
await b.close();
